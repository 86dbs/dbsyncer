CREATE TABLE `dbsyncer_group_rel` (
  `ID` varchar(64) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL COMMENT '唯一ID',
  `CREATE_TIME` bigint NOT NULL COMMENT '创建时间',
  `UPDATE_TIME` bigint NOT NULL COMMENT '修改时间',
  `GROUP_ID` varchar(64) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL COMMENT '分组ID',
  `TYPE` varchar(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL COMMENT '资源类型: connector/mapping/validateSync/databaseSync',
  `RESOURCE_ID` varchar(64) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL COMMENT '资源ID（连接或任务ID）',
  PRIMARY KEY (`ID`) USING BTREE,
  UNIQUE KEY `UK_GROUP_RESOURCE` (`GROUP_ID`, `TYPE`, `RESOURCE_ID`) USING BTREE,
  KEY `IDX_GROUP_RESOURCE` (`GROUP_ID`, `TYPE`) USING BTREE,
  KEY `IDX_RESOURCE` (`TYPE`, `RESOURCE_ID`) USING BTREE
) ENGINE = InnoDB CHARACTER SET = utf8mb4 COLLATE = utf8mb4_bin COMMENT = '业务分组关系表' ROW_FORMAT = Dynamic;
