CREATE TABLE `dbsyncer_cluster_node` (
  `ID` bigint NOT NULL AUTO_INCREMENT COMMENT '自增主键',
  `NODE_ID` varchar(64) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL COMMENT '节点ID，{ip}:{httpPort}',
  `CLUSTER_ID` varchar(64) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL COMMENT '集群标识',
  `NAME` varchar(128) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL COMMENT '展示名',
  `IP` varchar(64) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL COMMENT 'IP',
  `HTTP_PORT` int NOT NULL COMMENT 'Web端口',
  `RAFT_PORT` int NOT NULL COMMENT 'Raft RPC端口',
  `RAFT_PEER_ID` varchar(128) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL COMMENT 'Raft PeerId',
  `WORKER_ID` tinyint NOT NULL COMMENT '雪花worker.id，集群内唯一0-31，避免多节点生成配置/任务ID冲突',
  `ROLE` tinyint NOT NULL DEFAULT 0 COMMENT '0-FOLLOWER 1-LEADER 2-LEARNER',
  `STATUS` tinyint NOT NULL DEFAULT 0 COMMENT '0-JOINING 1-ONLINE 2-UNREACHABLE 3-OFFLINE 4-LEAVING',
  `NETWORK_OK` tinyint NOT NULL DEFAULT 1 COMMENT 'Leader探测是否可达',
  `TERM` bigint NOT NULL DEFAULT 0 COMMENT 'Raft term',
  `LAST_HEARTBEAT_TIME` bigint NOT NULL DEFAULT 0 COMMENT '最后心跳毫秒',
  `START_TIME` bigint NOT NULL DEFAULT 0 COMMENT '进程启动时间',
  `CREATE_TIME` bigint NOT NULL COMMENT '创建时间',
  `UPDATE_TIME` bigint NOT NULL COMMENT '修改时间',
  PRIMARY KEY (`ID`) USING BTREE,
  UNIQUE KEY `UK_CLUSTER_NODE` (`CLUSTER_ID`, `NODE_ID`) USING BTREE,
  UNIQUE KEY `UK_CLUSTER_WORKER` (`CLUSTER_ID`, `WORKER_ID`) USING BTREE,
  KEY `IDX_CLUSTER_STATUS` (`CLUSTER_ID`, `STATUS`) USING BTREE
) ENGINE = InnoDB CHARACTER SET = utf8mb4 COLLATE = utf8mb4_bin COMMENT = '集群节点表' ROW_FORMAT = Dynamic;
