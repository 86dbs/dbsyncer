CREATE TABLE `dbsyncer_resource_acl` (
  `ID` varchar(64) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL COMMENT '唯一ID',
  `CREATE_TIME` bigint NOT NULL COMMENT '创建时间',
  `UPDATE_TIME` bigint NOT NULL COMMENT '修改时间',
  `SUBJECT_TYPE` tinyint NOT NULL COMMENT '主体类型：0-USER;1-ROLE',
  `SUBJECT_ID` varchar(64) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL COMMENT '主体ID',
  `RESOURCE_TYPE` varchar(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL COMMENT '资源类型：group/connector/mapping/validateSync/databaseSync',
  `RESOURCE_ID` varchar(64) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL COMMENT '资源ID',
  `PERMISSION` tinyint NOT NULL COMMENT '0-只读,1-可读写',
  PRIMARY KEY (`ID`) USING BTREE,
  UNIQUE KEY `UK_RES_ACL` (`SUBJECT_TYPE`, `SUBJECT_ID`, `RESOURCE_TYPE`, `RESOURCE_ID`) USING BTREE,
  KEY `IDX_RES_ACL_RESOURCE` (`SUBJECT_ID`, `RESOURCE_TYPE`, `RESOURCE_ID`) USING BTREE,
  KEY `IDX_RES_ACL_BY_RES` (`RESOURCE_TYPE`, `RESOURCE_ID`) USING BTREE
) ENGINE = InnoDB CHARACTER SET = utf8mb4 COLLATE = utf8mb4_bin COMMENT = '资源权限关系表' ROW_FORMAT = Dynamic;
