CREATE TABLE `dbsyncer_table_group` (
  `ID` varchar(64) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL COMMENT '唯一ID',
  `CREATE_TIME` bigint NOT NULL COMMENT '创建时间',
  `UPDATE_TIME` bigint NOT NULL COMMENT '修改时间',
  `TASK_ID` varchar(64) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL COMMENT '任务ID',
  `SORT_INDEX` int NOT NULL DEFAULT 0 COMMENT '排序号',
  `SOURCE_CONNECTOR_ID` varchar(64) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL COMMENT '源库连接器ID',
  `TARGET_CONNECTOR_ID` varchar(64) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL COMMENT '目标库连接器ID',
  `SOURCE_DATABASE` varchar(128) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL COMMENT '源库',
  `TARGET_DATABASE` varchar(128) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL COMMENT '目标库',
  `SOURCE_SCHEMA` varchar(128) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL COMMENT '源schema',
  `TARGET_SCHEMA` varchar(128) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL COMMENT '目标schema',
  `SOURCE_TABLE` varchar(128) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL COMMENT '源表',
  `TARGET_TABLE` varchar(128) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL COMMENT '目标表',
  `SOURCE_TOTAL` bigint NOT NULL DEFAULT 0 COMMENT '源表总数',
  `TARGET_TOTAL` bigint NOT NULL DEFAULT 0 COMMENT '目标表总数',
  `JSON` mediumtext CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL COMMENT '配置信息',
  PRIMARY KEY (`ID`) USING BTREE,
  KEY `IDX_TASK_ID` (`TASK_ID`, `SORT_INDEX`) USING BTREE,
  KEY `IDX_TG_MAPPING` (`TASK_ID`, `SOURCE_CONNECTOR_ID`, `TARGET_CONNECTOR_ID`, `SOURCE_DATABASE`, `TARGET_DATABASE`, `SOURCE_SCHEMA`, `TARGET_SCHEMA`, `SORT_INDEX`) USING BTREE,
  KEY `IDX_SOURCE_CONN_ID` (`SOURCE_CONNECTOR_ID`) USING BTREE,
  KEY `IDX_TARGET_CONN_ID` (`TARGET_CONNECTOR_ID`) USING BTREE
) ENGINE = InnoDB CHARACTER SET = utf8mb4 COLLATE = utf8mb4_bin COMMENT = '表映射关系配置表' ROW_FORMAT = Dynamic;
