CREATE TABLE `dbsyncer_capture_task` (
  `ID` varchar(64) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL COMMENT '唯一ID',
  `CREATE_TIME` bigint NOT NULL COMMENT '创建时间',
  `UPDATE_TIME` bigint NOT NULL COMMENT '修改时间',
  `NAME` varchar(50) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL COMMENT '采集任务名称',
  `AGENT_HOST` varchar(128) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL COMMENT 'Agent主机',
  `AGENT_PORT` int NOT NULL COMMENT 'Agent端口',
  `AGENT_SECRET` varchar(256) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL COMMENT 'AGENT密钥，密文',
  `QUEUE_CAPACITY` int NOT NULL DEFAULT 100000 COMMENT '事件队列容量',
  `STATE` tinyint NOT NULL DEFAULT 0 COMMENT '状态，0-停止 1-运行',
  `PUBLIC_KEY` text CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL COMMENT '公钥',
  `PRIVATE_KEY` text CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL COMMENT '私钥，密文',
  PRIMARY KEY (`ID`) USING BTREE,
  KEY `IDX_AGENT` (`AGENT_HOST`, `AGENT_PORT`) USING BTREE,
  KEY `IDX_UPDATE_TIME` (`UPDATE_TIME`) USING BTREE
) ENGINE = InnoDB CHARACTER SET = utf8mb4 COLLATE = utf8mb4_bin COMMENT = '采集任务表' ROW_FORMAT = Dynamic;
